/** 全量诗库（去重） */
export const POEMS: string[] = [...new Set(LINES)];

/** 令字池：只用诗句够多的字（>=8 句），否则一轮都撑不满 */
export const RHYME_CHARS: string[] = (() => {
  const counts = new Map<string, number>();
  for (const line of POEMS) {
    for (const ch of new Set(line.split(""))) {
      counts.set(ch, (counts.get(ch) ?? 0) + 1);
    }
  }
  const pool = ["春", "月", "花", "风", "山", "水", "云", "雪", "夜", "江"];
  return pool.filter((ch) => (counts.get(ch) ?? 0) >= 8);
})();

/** 含某字的诗句列表 */
export function linesWith(ch: string): string[] {
  return POEMS.filter((line) => line.includes(ch));
}

/** 含某字、且未被用过的诗句还剩几条 */
export function countAvailable(ch: string, used: Set<string>): number {
  let n = 0;
  for (const line of POEMS) if (line.includes(ch) && !used.has(line)) n++;
  return n;
}
