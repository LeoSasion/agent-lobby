/** 全量词库：基础 + 补充，去重（首字索引与「还剩几条」都依赖唯一性） */
export const IDIOMS: string[] = [...new Set([...BASE, ...EXTRA])];

/** 去重后的词库（构建期做一次，运行期不再重复算） */
export const IDIOM_SET: Set<string> = new Set(IDIOMS);

/** 首字 → 该字开头的成语列表（接龙用） */
export const BY_FIRST: Map<string, string[]> = (() => {
  const m = new Map<string, string[]>();
  for (const w of IDIOMS) {
    const k = w[0]!;
    if (!m.has(k)) m.set(k, []);
    m.get(k)!.push(w);
  }
  return m;
})();

/** 某成语的尾字（接龙要继续的那个字） */
export function tailOf(idiom: string): string {
  return idiom[idiom.length - 1] ?? "";
}

/** 某成语的首字 */
export function headOf(idiom: string): string {
  return idiom[0] ?? "";
}

/** 以某字开头的成语个数（可用作「还剩几条」提示） */
export function countByFirst(ch: string): number {
  return BY_FIRST.get(ch)?.length ?? 0;
}
